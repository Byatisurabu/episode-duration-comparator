# app/config.py
#
# Единственное место для настройки порогов и цветов индикации различий.
# После изменения значений достаточно перезапустить приложение.


class DiffThresholds:
    """
    Пороговые значения для классификации различий длительности.

    Логика (приоритет сверху вниз):
      1. abs(diff_min) <= MINUTES_INSIGNIFICANT  → small-diff (серый)
      2. abs(diff_percent) < PERCENT_SMALL       → small-diff (серый)
      3. abs(diff_percent) < PERCENT_MEDIUM      → medium-diff (жёлтый)
      4. иначе                                   → large-red / large-green
    """

    # Абсолютная разница в минутах, при которой различие считается незначительным.
    # Имеет приоритет над процентным порогом.
    MINUTES_INSIGNIFICANT: int = 2

    # Граница между «незначительным» (серый) и «небольшим» (жёлтый).
    PERCENT_SMALL: float = 3.0

    # Граница между «небольшим» (жёлтый) и «значимым» (красный/зелёный).
    # Используется также для заливки всей строки.
    PERCENT_MEDIUM: float = 5.0


class DiffColors:
    """
    Цвета индикации различий. Используются как CSS-переменные в main.css
    и передаются в шаблоны для легенды.

    Формат: CSS hex-цвет (#rrggbb).
    """

    # Цвета шрифта в ячейках таблицы
    SMALL: str = "#6b7280"    # серый     — незначительная разница
    MEDIUM: str = "#d97706"   # янтарный  — небольшая разница (PERCENT_SMALL..PERCENT_MEDIUM)
    LARGE_RED: str = "#dc2626"   # красный   — значимое сокращение (≥ PERCENT_MEDIUM)
    LARGE_GREEN: str = "#16a34a" # зелёный   — значимое увеличение (≥ PERCENT_MEDIUM)

    # Цвета заливки всей строки при значимом расхождении
    ROW_HIGHLIGHT_RED: str = "#fef2f2"    # светло-красный фон — сокращение
    ROW_HIGHLIGHT_GREEN: str = "#f0fdf4"  # светло-зелёный фон — увеличение
